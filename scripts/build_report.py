"""Write RESULTS.md and index.html (the GitHub Pages site) from results/*.json."""
import html, json, os, sys
from collections import defaultdict

ROOT = os.path.join(os.path.dirname(__file__), "..")
R = lambda p: os.path.join(ROOT, p)


def load(p):
    return json.load(open(R(p))) if os.path.exists(R(p)) else None


def verdict(r):
    if r["verdict"] == "exact":
        return "exact"
    q = r["test_nmse"] / r["oracle_nmse"]
    if q < 0.99:
        return "beats"
    return "equivalent" if q <= 1.01 else "miss"


def world_tables(rows):
    conds = list(dict.fromkeys(r["condition"] for r in rows))
    worlds = list(dict.fromkeys(r["world"] for r in rows))
    methods = [("residue", "Luotain2 (residue-guided)"), ("stlsq", "fixed library + STLSQ"), ("random", "random proposals")]
    md, ht = [], []
    for cond in conds:
        md.append(f"\n**{cond} noise** — verdicts over seeds; × = median held-out error ÷ true-law error\n")
        md.append("| world | " + " | ".join(l for _, l in methods) + " |")
        md.append("|---|" + "---:|" * len(methods))
        hrows = []
        for w in worlds:
            cells = []
            for m, _ in methods:
                sub = [r for r in rows if r["condition"] == cond and r["world"] == w and r["method"] == m]
                if not sub:
                    cells.append("–")
                    continue
                v = [verdict(r) for r in sub]
                ratios = sorted(r["test_nmse"] / r["oracle_nmse"] for r in sub)
                med = ratios[len(ratios) // 2]
                parts = [f"{v.count(k)} {lab}" for k, lab in (("exact", "exact"), ("equivalent", "equiv"), ("beats", "beats-truth")) if v.count(k)]
                cells.append((", ".join(parts) or "0") + f" of {len(sub)} · ×{med:.3g}")
            md.append(f"| {w} | " + " | ".join(cells) + " |")
            hrows.append((w, cells))
        ht.append((cond, [l for _, l in methods], hrows))
    return "\n".join(md), ht


def main():
    worlds = load("results/worlds.json") or []
    images = load("results/images.json") or {}
    video = load("results/video_cockatoo.json")
    stress = load("results/stress.json") or []
    md_worlds, ht_worlds = world_tables(worlds + stress)
    # images
    img_md = ["| image | terms | reach (px) | raw | JPEG-LS median | LS radius 1 | LS radius 2 | **discovered law** |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    img_rows = []
    for k, o in images.items():
        if "bpp_med" not in o:
            continue
        best_fixed = min(o["bpp_med"], o["bpp_ls_r1"], o["bpp_ls_r2"])
        mark = "**" if o["bpp_law"] < best_fixed else ""
        img_md.append(f"| {k} | {o['n_terms']} | {o['reach']} | {o['bpp_raw']:.3f} | {o['bpp_med']:.3f} | {o['bpp_ls_r1']:.3f} | {o['bpp_ls_r2']:.3f} | {mark}{o['bpp_law']:.3f}{mark} |")
        img_rows.append((k, o, o["bpp_law"] < best_fixed))
    syn = images.get("synthetic AR texture")
    out = ["# Luotain2 results", "", "Generated by `scripts/build_report.py` from `results/*.json`.", "",
           "## Mystery worlds", md_worlds, "",
           "Exact = the discovered law has exactly the true terms. Equiv = different terms, held-out error within 1% of the true law refitted on the same data (the oracle). Beats-truth = different terms that predict held-out data *better* than the true law: this happens with measurement noise, where averaging earlier noisy frames cleans the input, so the best predictor is not the law. Anything else is a miss.", "",
           "## Still images (lossless-coding predictors, bits per pixel on the held-out bottom band)", "",
           "\n".join(img_md), ""]
    if syn:
        out += [f"Synthetic texture with a known causal law: exact = {syn['exact']}. Found `{syn['law']}`; truth `{syn['truth']}`.", ""]
    if video:
        out += ["## Real video (cockatoo.mp4, 90×160 grey, last 30% of frames held out)", "",
                f"| predictor | terms | test NMSE |", "|---|---:|---:|",
                f"| nothing changes (hold-last) | 1 | {video['hold_last']:.4f} |",
                f"| fixed library + STLSQ | {video['library_terms']} | {video['library_test']:.4f} |",
                f"| discovered law | {video['law_terms']} | {video['law_test']:.4f} |", "",
                f"Discovered: `{video['law']}`", ""]
    open(R("RESULTS.md"), "w").write("\n".join(out))

    # ---------- site ----------
    e = html.escape
    def table_html(cond, heads, rows):
        h = "".join(f"<th>{e(x)}</th>" for x in heads)
        b = "".join("<tr><th scope='row'>" + e(w) + "</th>" + "".join(f"<td>{e(c)}</td>" for c in cells) + "</tr>" for w, cells in rows)
        return f"<h3>{e(cond)} noise</h3><div class='scroll'><table><thead><tr><th>world</th>{h}</tr></thead><tbody>{b}</tbody></table></div>"
    worlds_html = "".join(table_html(*t) for t in ht_worlds)
    img_html = "".join(
        f"<tr><th scope='row'>{e(k)}</th><td>{o['n_terms']}</td><td>{o['reach']}</td><td>{o['bpp_med']:.3f}</td><td>{o['bpp_ls_r2']:.3f}</td><td class='{'win' if win else ''}'>{o['bpp_law']:.3f}</td></tr>"
        for k, o, win in img_rows)
    vid_html = ""
    if video:
        vid_html = (f"<p>Real footage (cockatoo.mp4). Test error: hold-last {video['hold_last']:.4f}, "
                    f"fixed library ({video['library_terms']} terms) {video['library_test']:.4f}, "
                    f"discovered law ({video['law_terms']} terms) {video['law_test']:.4f}. "
                    f"A bird is not a sparse law; the dense regression wins here.</p>")
    page = open(R("site/template.html")).read()
    page = page.replace("{{WORLDS}}", worlds_html).replace("{{IMAGES}}", img_html).replace("{{VIDEO}}", vid_html)
    if syn:
        page = page.replace("{{SYNTH}}", e(f"Found {syn['law']}  ·  truth {syn['truth']}"))
    open(R("index.html"), "w").write(page)
    print("wrote RESULTS.md and index.html")


if __name__ == "__main__":
    main()
